-- 目的:
--   rbac_user 表新增 gender (性别) 字段, 用于部门管理页"显示部门用户"开关
--   在部门树内为每个用户渲染性别 icon.
-- 业务约束:
--   gender 枚举: 0=未知 1=男 2=女
--   默认 0 (未知), 不强制录入; 部门树显示用户时若为 0 渲染灰色 icon + "未知"
-- 表: rbac_user
-- 兼容: IF NOT EXISTS 兜底, 幂等
-- =============================================================================

ALTER TABLE rbac_user
    ADD COLUMN gender TINYINT NOT NULL DEFAULT 0 COMMENT '性别: 0=未知 1=男 2=女';
