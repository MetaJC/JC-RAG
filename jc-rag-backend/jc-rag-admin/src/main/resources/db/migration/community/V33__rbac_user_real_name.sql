-- 目的:
--   rbac_user 表新增 real_name (真实姓名) 字段, 用于在用户列表 / 详情弹窗展示,
--   与 nickname (昵称) 区分; 后台管理端添加 / 编辑用户时支持编辑.
-- 业务约束:
--   - real_name 与 nickname 可不同; 真实姓名是用户实际姓名, 昵称是用户偏好
--   - 前端表单必填, 后端仅做长度校验 (max 50); 历史数据允许为空字符串
--   - 默认 '' 兼容存量数据
-- 表: rbac_user
-- 兼容: IF NOT EXISTS 兜底, 幂等
-- =============================================================================

ALTER TABLE rbac_user
    ADD COLUMN real_name VARCHAR(50) NOT NULL DEFAULT '' COMMENT '真实姓名';
